#!/usr/bin/env python3
"""T-425 (the user, 2026-10-18: "we should also have these same tunes on the devices (and tab5 and phone) -- so everything
feels in sync"): DAEMONS' own harp and flute (server/data/sounds/, written by DAEMONS tools/geninstruments.py -- the
project's own, nothing of Nintendo's) as a C header and a Swift file, so whatever plays samples away from the app's
bundle (the Tab5, the phone widget's buttons) has them without the companion: each WAV's samples, and how instruments.json says to pitch, loop and shape them. The small boards keep their
beeps on the same notes.

    firmware/common/instruments.h                       the Tab5's (samples as arrays)
    app/targets/widget/_shared/Instruments.swift        the phone widget's buttons (samples as base64: a Swift array
                                                        literal this long takes the compiler minutes)

    python3 firmware/common/instruments.py            report what would change
    python3 firmware/common/instruments.py --write    write it
"""
import base64, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SOUNDS = os.path.join(ROOT, "server", "data", "sounds")
OUT = os.path.join(HERE, "instruments.h")
SWIFT = os.path.join(ROOT, "app", "targets", "widget", "_shared", "Instruments.swift")


def pcm(path):
    b = open(path, "rb").read()
    at = 12
    while at + 8 <= len(b):
        cid, n = b[at:at + 4], struct.unpack("<I", b[at + 4:at + 8])[0]
        if cid == b"fmt ":
            fmt, ch, rate, _, _, bits = struct.unpack("<HHIIHH", b[at + 8:at + 24])
            if (fmt, ch, bits) != (1, 1, 16):
                raise SystemExit(f"instruments.py: {path} is not mono 16-bit PCM")
        if cid == b"data":
            return list(struct.unpack(f"<{n // 2}h", b[at + 8:at + 8 + n - (n & 1)]))
        at += 8 + n + (n & 1)
    raise SystemExit(f"instruments.py: no samples in {path}")


def header():
    spec = json.load(open(os.path.join(SOUNDS, "instruments.json")))
    lines = ["// Generated by firmware/common/instruments.py from server/data/sounds/ (DAEMONS tools/geninstruments.py) -- edit",
             "// those, not this. T-425: DAEMONS' own harp (a CONTENT save) and flute (CONTEXT), one voice for the game and every",
             "// screen; each one note at root_midi, pitched by playing it faster or slower, looped between loop_start and",
             "// loop_end (-1: no loop, played out), under its envelope.",
             "#pragma once",
             "#include <stdint.h>",
             "",
             "struct Instrument { const char *name, *edition; const int16_t *pcm; uint32_t n; uint32_t rate; int root;",
             "                    int32_t loopStart, loopEnd; uint16_t attackMs, decayMs, releaseMs; float sustain; };"]
    table = []
    for name in [k for k in spec if not k.startswith("_")]:
        s = spec[name]
        data = pcm(os.path.join(SOUNDS, s["file"]))
        ident = f"INSTRUMENT_{name.upper()}"
        lines.append(f"static const int16_t {ident}[{len(data)}] = {{")
        lines += ["  " + ", ".join(str(v) for v in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
        lines.append("};")
        loop = lambda v: -1 if v is None else int(v)
        table.append(f'  {{ "{name}", "{s["edition"]}", {ident}, {len(data)}, {s["sample_rate"]}, {s["root_midi"]}, '
                     f'{loop(s["loop_start"])}, {loop(s["loop_end"])}, {s["attack_ms"]}, {s["decay_ms"]}, {s["release_ms"]}, {float(s["sustain"])}f }},')
    lines.append(f"static const Instrument INSTRUMENTS[{len(table)}] = {{")
    lines += table
    lines.append("};")
    lines.append(f"static const int INSTRUMENT_N = {len(table)};")
    return "\n".join(lines) + "\n"


def swift():
    spec = json.load(open(os.path.join(SOUNDS, "instruments.json")))
    lines = ["// Generated by firmware/common/instruments.py from server/data/sounds/ (DAEMONS tools/geninstruments.py) -- edit",
             "// those, not this. T-425: DAEMONS' own harp (a CONTENT save) and flute (CONTEXT) for the widget's buttons, as the",
             "// app and the Tab5 play them; each one note at `root`, its samples mono 16-bit little-endian, in base64.",
             "import Foundation",
             "",
             "struct InstrumentSpec {",
             "  let name: String; let edition: String; let rate: Int; let root: Int",
             "  let loopStart: Int; let loopEnd: Int          // -1: no loop, played out",
             "  let attackMs: Int; let decayMs: Int; let releaseMs: Int; let sustain: Double",
             "  let samples64: String",
             "}",
             "",
             "enum Instruments {",
             "  static let all: [InstrumentSpec] = ["]
    for name in [k for k in spec if not k.startswith("_")]:
        s = spec[name]
        data = pcm(os.path.join(SOUNDS, s["file"]))
        b64 = base64.b64encode(struct.pack(f"<{len(data)}h", *data)).decode()
        loop = lambda v: -1 if v is None else int(v)
        lines.append(f'    InstrumentSpec(name: "{name}", edition: "{s["edition"]}", rate: {s["sample_rate"]}, root: {s["root_midi"]},')
        lines.append(f'                   loopStart: {loop(s["loop_start"])}, loopEnd: {loop(s["loop_end"])}, attackMs: {s["attack_ms"]}, '
                     f'decayMs: {s["decay_ms"]}, releaseMs: {s["release_ms"]}, sustain: {float(s["sustain"])},')
        lines.append(f'                   samples64: "{b64}"),')
    lines += ["  ]", "}"]
    return "\n".join(lines) + "\n"


def main():
    for path, body in ((OUT, header()), (SWIFT, swift())):
        rel = os.path.relpath(path, ROOT)
        old = open(path).read() if os.path.exists(path) else None
        if old == body:
            print(f"  instruments: {rel} unchanged")
        elif "--write" in sys.argv:
            open(path, "w").write(body)
            print(f"  instruments: written: {rel}")
        else:
            print(f"  instruments: would write: {rel}")


if __name__ == "__main__":
    main()
