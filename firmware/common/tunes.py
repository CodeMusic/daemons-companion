#!/usr/bin/env python3
"""C-160 (the user, 2026-10-18: "phone should have same sounds as game/device, all should be in sync"): the boards' and
the Tab5's tunes (firmware/common/tunes.h, the one copy) as JSON for the app and the site, so the phone plays the same
notes and never keeps a list of its own.

    server/data/tunes.json   {"tunes": {"SLOTS_PULL": [[semis, ms], ...], ...}, "wakeBase": 73}

Each tune is notes in semitones over a base -- the day's note (C-73: Sunday C ... Saturday B, the octave above middle C)
for everything but the wake jingle, which plays on WAKE_BASE -- and 127 is a rest, as in tunes.h. The scales
(TUNE_PENTA, TUNE_GAME_PENTA) come along as lists of semitones.

    python3 firmware/common/tunes.py            report what would change
    python3 firmware/common/tunes.py --write    write server/data/tunes.json
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, "tunes.h")
OUT = os.path.join(ROOT, "server", "data", "tunes.json")


def parse(text):
    tunes = {}
    for name, body in re.findall(r"static const Note TUNE_(\w+)\[\]\s*=\s*\{(.*?)\};", text, re.S):
        notes = [[int(a), int(b)] for a, b in re.findall(r"\{\s*(-?\d+)\s*,\s*(\d+)\s*\}", body)]
        if not notes:
            raise SystemExit(f"tunes.py: TUNE_{name} has no notes I can read -- has tunes.h changed shape?")
        tunes[name] = notes
    scales = {name: [int(x) for x in re.findall(r"-?\d+", body)]
              for name, body in re.findall(r"static const int8_t TUNE_(\w+)\[\]\s*=\s*\{(.*?)\};", text, re.S)}
    m = re.search(r"static const int WAKE_BASE\s*=\s*(\d+)\s*\+\s*(\d+)", text)
    if not tunes or not m:
        raise SystemExit("tunes.py: no tunes, or no WAKE_BASE, in tunes.h -- has it changed shape?")
    return {"_about": "Generated by firmware/common/tunes.py from firmware/common/tunes.h -- edit that, not this. "
                      "Notes are [semitones over the base, ms]; 127 is a rest. The base is the day's note (MIDI 72 C .. 83 B), "
                      "the wake jingle's wakeBase.",
            "tunes": tunes, "scales": scales, "wakeBase": int(m.group(1)) + int(m.group(2))}


def main():
    data = parse(open(SRC, encoding="utf-8").read())
    text = json.dumps(data, indent=1) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old == text:
        print(f"tunes.py: server/data/tunes.json is current ({len(data['tunes'])} tunes)")
        return
    if "--write" not in sys.argv:
        print(f"tunes.py: would write server/data/tunes.json ({len(data['tunes'])} tunes)")
        return
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"tunes.py: wrote server/data/tunes.json ({len(data['tunes'])} tunes)")


if __name__ == "__main__":
    main()
