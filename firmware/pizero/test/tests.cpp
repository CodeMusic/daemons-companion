static int failed = 0;
#define CHECK(what, ok) do { if (!(ok)) { printf("FAILED: %s\n", what); failed++; } else printf("ok: %s\n", what); } while (0)

static Bytes xorshift(size_t n, uint32_t x) {   // the same bytes make_vectors drew
  Bytes out;
  for (size_t i = 0; i < n; i++) { x ^= x << 13; x ^= x >> 17; x ^= x << 5; out.push_back((uint8_t)x); }
  return out;
}
template <typename F> static bool refuses(F f) { try { f(); } catch (const PatchError &) { return true; } return false; }

int main() {
  const char *abc = "abc";
  CHECK("sha1 of abc", sha1Hex((const uint8_t *)abc, 3) == "a9993e364706816aba3e25717850c26c9cd0d89d");
  CHECK("sha1 of nothing", sha1Hex(nullptr, 0) == "da39a3ee5e6b4b0d3255bfef95601890afd80709");
  std::string m(1000000, 'a');
  CHECK("sha1 of a million a's", sha1Hex((const uint8_t *)m.data(), m.size()) == "34aa973cd4c4daa4f61eeb2bdbad27316534016f");
  std::string l = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";   // 56 bytes: the padding's second block
  CHECK("sha1 across the padding's edge", sha1Hex((const uint8_t *)l.data(), l.size()) == "84983e441c3bd26ebaae4aa1f95129e5e54670f1");
  CHECK("crc32 of 123456789", crc32((const uint8_t *)"123456789", 9) == 0xCBF43926u);

  const Bytes source = xorshift(8192, 2463534242u), patch(PATCH, PATCH + sizeof PATCH);
  Bytes made;
  bool threw = refuses([&] { made = applyBps(source, patch); });
  CHECK("bps applies bps.py's patch", !threw && made.size() == TARGET_SIZE && sha1Hex(made) == TARGET_SHA1);

  Bytes tc(TARGET_COPY, TARGET_COPY + sizeof TARGET_COPY), out;
  threw = refuses([&] { out = applyBps(Bytes(), tc); });
  CHECK("bps TargetCopy overlapping", !threw && std::string(out.begin(), out.end()) == "abababab");

  Bytes damaged = patch;
  damaged[40] ^= 1;
  CHECK("bps refuses a damaged patch", refuses([&] { applyBps(source, damaged); }));
  Bytes other = source;
  other[5] ^= 1;
  CHECK("bps refuses a ROM it was not made for", refuses([&] { applyBps(other, patch); }));
  CHECK("bps refuses what is not a patch", refuses([&] { applyBps(source, Bytes(20, 0)); }));
  Bytes shortSource(source.begin(), source.end() - 1);
  CHECK("bps refuses a ROM of the wrong size", refuses([&] { applyBps(shortSource, patch); }));

  // C-461: StackFlow's objects found by their braces -- split across reads, a brace inside a string, a boot line between
  {
    stackflow::Reader r;
    std::vector<std::string> got;
    const std::string a = "boot text {\"a\":\"x}{\\\"\",\"b\":{\"c\":1}}\n{\"d\"";
    const std::string b = ":2}junk{\"e\":\"}\"}";
    r.feed(a.data(), a.size(), got);
    CHECK("stackflow: an object whole, a brace in a string not counted", got.size() == 1 && got[0] == "{\"a\":\"x}{\\\"\",\"b\":{\"c\":1}}");
    r.feed(b.data(), b.size(), got);
    CHECK("stackflow: an object split across reads, junk between dropped", got.size() == 3 && got[1] == "{\"d\":2}" && got[2] == "{\"e\":\"}\"}");
    CHECK("stackflow: escaped as JSON", stackflow::escape("say \"hi\"\n") == "say \\\"hi\\\"\\n");
  }
  // C-459: the charge rule -- a charger lifts it; the lower charge rules; above 40 asked, 10..40 override, below 10 refused
  {
    kit::Limits l;
    CHECK("kit: charging goes", kit::mayWake(5, true, 3, false, l) == kit::Wake::Go);
    CHECK("kit: plenty asks", kit::mayWake(80, false, -1, false, l) == kit::Wake::Ask);
    CHECK("kit: the lower charge rules", kit::mayWake(80, false, 30, false, l) == kit::Wake::Override);
    CHECK("kit: near empty refuses", kit::mayWake(9, false, 90, false, l) == kit::Wake::Refuse);
    CHECK("kit: at the line is override", kit::mayWake(40, false, -1, false, l) == kit::Wake::Override);
    l.alwaysAsk = false;
    CHECK("kit: always yes goes", kit::mayWake(70, false, -1, false, l) == kit::Wake::Go);
    CHECK("kit: always yes still refuses near empty", kit::mayWake(8, false, -1, false, l) == kit::Wake::Refuse);
  }

  printf(failed ? "%d FAILED\n" : "all passed\n", failed);
  return failed ? 1 : 0;
}
